%BUILD_SIMULINK_IK_TEST Build and run an IK -> FK Simulink tracking test.
% Creates ik_fk_simulink_test.slx and ik_fk_test_plot.png in this folder.

folder = fileparts(mfilename('fullpath'));
modelName = 'ik_fk_simulink_test';
modelFile = fullfile(folder, [modelName '.slx']);
plotFile = fullfile(folder, 'ik_fk_test_plot.png');

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
if exist(modelFile, 'file')
    delete(modelFile);
end
load_system('simulink');
new_system(modelName);

% A small smooth joint trajectory keeps the IK solution on one continuous branch.
qBias = deg2rad([0, 20, -30, 0, 45, 0]);
qAmplitude = deg2rad([5, 8, 6, 10, 8, 12]);
qFrequency = [0.35, 0.30, 0.25, 0.20, 0.18, 0.15];

for joint = 1:6
    block = sprintf('%s/Joint%d', modelName, joint);
    add_block('simulink/Sources/Sine Wave', block, ...
        'Position', [30, 30 + 60*(joint-1), 100, 60 + 60*(joint-1)], ...
        'Amplitude', num2str(qAmplitude(joint), 16), ...
        'Bias', num2str(qBias(joint), 16), ...
        'Frequency', num2str(qFrequency(joint), 16), ...
        'Phase', '0');
end

add_block('simulink/Signal Routing/Mux', [modelName '/ReferenceJoints'], ...
    'Inputs', '6', 'Position', [140, 105, 145, 225]);

fkScript = sprintf([ ...
    'function T = fkTransform(q)\n' ...
    '%%#codegen\n' ...
    'a = [0; 607; 568; 0; 0; 0];\n' ...
    'alpha = [-pi/2; 0; 0; pi/2; -pi/2; 0];\n' ...
    'd = [176.5; 193; -127; 125; 125; 111.3];\n' ...
    'offset = [0; -pi/2; 0; pi/2; 0; 0];\n' ...
    'T = eye(4);\n' ...
    'for k = 1:6\n' ...
    '    th = q(k) + offset(k);\n' ...
    '    ct = cos(th); st = sin(th);\n' ...
    '    ca = cos(alpha(k)); sa = sin(alpha(k));\n' ...
    '    A = [ct, -st*ca, st*sa, a(k)*ct; ...\n' ...
    '         st,  ct*ca,-ct*sa, a(k)*st; ...\n' ...
    '          0,     sa,    ca, d(k); ...\n' ...
    '          0,      0,     0, 1];\n' ...
    '    T = T * A;\n' ...
    'end\n' ...
    'end\n']);

targetBlock = [modelName '/DesiredPoseFK'];
add_block('simulink/User-Defined Functions/MATLAB Function', targetBlock, ...
    'Position', [205, 105, 350, 165]);
targetChart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', targetBlock);
targetChart.Script = fkScript;

ikBlock = [modelName '/IKTracker'];
add_block('simulink/User-Defined Functions/MATLAB Function', ikBlock, ...
    'Position', [420, 85, 600, 190]);
ikScript = sprintf([ ...
    'function [qEstimate, poseError] = ikTrack(Tdes)\n' ...
    '%%#codegen\n' ...
    'persistent q\n' ...
    'if isempty(q)\n' ...
    '    q = [0; 20*pi/180; -30*pi/180; 0; 45*pi/180; 0];\n' ...
    'end\n' ...
    'a = [0; 607; 568; 0; 0; 0];\n' ...
    'alpha = [-pi/2; 0; 0; pi/2; -pi/2; 0];\n' ...
    'd = [176.5; 193; -127; 125; 125; 111.3];\n' ...
    'offset = [0; -pi/2; 0; pi/2; 0; 0];\n' ...
    'for iteration = 1:8\n' ...
    '    T = eye(4); origins = zeros(3,6); axes = zeros(3,6);\n' ...
    '    for k = 1:6\n' ...
    '        origins(:,k) = T(1:3,4); axes(:,k) = T(1:3,3);\n' ...
    '        th = q(k) + offset(k);\n' ...
    '        ct = cos(th); st = sin(th); ca = cos(alpha(k)); sa = sin(alpha(k));\n' ...
    '        A = [ct, -st*ca, st*sa, a(k)*ct; st, ct*ca, -ct*sa, a(k)*st; ...\n' ...
    '             0, sa, ca, d(k); 0, 0, 0, 1];\n' ...
    '        T = T*A;\n' ...
    '    end\n' ...
    '    ep = Tdes(1:3,4)-T(1:3,4);\n' ...
    '    Rerr = Tdes(1:3,1:3)*T(1:3,1:3).'';\n' ...
    '    cang = min(1,max(-1,(trace(Rerr)-1)/2)); ang = acos(cang);\n' ...
    '    sv = [Rerr(3,2)-Rerr(2,3); Rerr(1,3)-Rerr(3,1); Rerr(2,1)-Rerr(1,2)];\n' ...
    '    if ang < 1e-8\n' ...
    '        er = 0.5*sv;\n' ...
    '    else\n' ...
    '        er = ang/(2*sin(ang))*sv;\n' ...
    '    end\n' ...
    '    J = zeros(6,6);\n' ...
    '    for k = 1:6\n' ...
    '        J(1:3,k) = cross(axes(:,k),T(1:3,4)-origins(:,k));\n' ...
    '        J(4:6,k) = axes(:,k);\n' ...
    '    end\n' ...
    '    J(4:6,:) = 500*J(4:6,:);\n' ...
    '    e = [ep; 500*er];\n' ...
    '    dq = (J.''*J+1e-3*eye(6))\\(J.''*e);\n' ...
    '    ndq = norm(dq); if ndq > 0.15, dq = dq*(0.15/ndq); end\n' ...
    '    q = q+dq;\n' ...
    'end\n' ...
    'qEstimate = q;\n' ...
    'T = eye(4);\n' ...
    'for k = 1:6\n' ...
    '    th = q(k)+offset(k); ct=cos(th); st=sin(th); ca=cos(alpha(k)); sa=sin(alpha(k));\n' ...
    '    A=[ct,-st*ca,st*sa,a(k)*ct; st,ct*ca,-ct*sa,a(k)*st; 0,sa,ca,d(k); 0,0,0,1];\n' ...
    '    T=T*A;\n' ...
    'end\n' ...
    'ep=Tdes(1:3,4)-T(1:3,4); Rerr=Tdes(1:3,1:3)*T(1:3,1:3).'';\n' ...
    'cang=min(1,max(-1,(trace(Rerr)-1)/2)); ang=acos(cang);\n' ...
    'sv=[Rerr(3,2)-Rerr(2,3); Rerr(1,3)-Rerr(3,1); Rerr(2,1)-Rerr(1,2)];\n' ...
    'if ang<1e-8, er=0.5*sv; else, er=ang/(2*sin(ang))*sv; end\n' ...
    'poseError=[norm(ep); ang*180/pi];\n' ...
    'end\n']);
ikChart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', ikBlock);
ikChart.Script = ikScript;

actualBlock = [modelName '/SolutionFK'];
add_block('simulink/User-Defined Functions/MATLAB Function', actualBlock, ...
    'Position', [670, 95, 810, 155]);
actualChart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', actualBlock);
actualChart.Script = fkScript;

compareBlock = [modelName '/ComparePose'];
add_block('simulink/User-Defined Functions/MATLAB Function', compareBlock, ...
    'Position', [875, 95, 1035, 165]);
compareChart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', compareBlock);
compareChart.Script = sprintf([ ...
    'function positions = comparePose(Tdes,Tactual)\n' ...
    '%%#codegen\n' ...
    'positions=[Tdes(1:3,4);Tactual(1:3,4)];\n' ...
    'end\n']);

add_block('simulink/Sinks/Scope', [modelName '/PositionErrorScope'], ...
    'Position', [670, 205, 725, 265]);
add_block('simulink/Sinks/Scope', [modelName '/PoseCompareScope'], ...
    'Position', [1085, 100, 1140, 170]);
add_block('simulink/Sinks/To Workspace', [modelName '/PoseErrorToWorkspace'], ...
    'VariableName', 'pose_error_ts', 'SaveFormat', 'Timeseries', ...
    'Position', [670, 285, 785, 320]);
add_block('simulink/Sinks/To Workspace', [modelName '/PoseCompareToWorkspace'], ...
    'VariableName', 'pose_compare_ts', 'SaveFormat', 'Timeseries', ...
    'Position', [1085, 200, 1200, 235]);
add_block('simulink/Sinks/To Workspace', [modelName '/JointReferenceToWorkspace'], ...
    'VariableName', 'joint_reference_ts', 'SaveFormat', 'Timeseries', ...
    'Position', [140, 265, 260, 300]);
add_block('simulink/Sinks/To Workspace', [modelName '/JointSolutionToWorkspace'], ...
    'VariableName', 'joint_solution_ts', 'SaveFormat', 'Timeseries', ...
    'Position', [420, 230, 545, 265]);

for joint = 1:6
    add_line(modelName, sprintf('Joint%d/1', joint), ...
        sprintf('ReferenceJoints/%d', joint), 'autorouting', 'on');
end
add_line(modelName, 'ReferenceJoints/1', 'DesiredPoseFK/1', 'autorouting', 'on');
add_line(modelName, 'ReferenceJoints/1', 'JointReferenceToWorkspace/1', 'autorouting', 'on');
add_line(modelName, 'DesiredPoseFK/1', 'IKTracker/1', 'autorouting', 'on');
add_line(modelName, 'IKTracker/1', 'SolutionFK/1', 'autorouting', 'on');
add_line(modelName, 'IKTracker/1', 'JointSolutionToWorkspace/1', 'autorouting', 'on');
add_line(modelName, 'IKTracker/2', 'PositionErrorScope/1', 'autorouting', 'on');
add_line(modelName, 'IKTracker/2', 'PoseErrorToWorkspace/1', 'autorouting', 'on');
add_line(modelName, 'DesiredPoseFK/1', 'ComparePose/1', 'autorouting', 'on');
add_line(modelName, 'SolutionFK/1', 'ComparePose/2', 'autorouting', 'on');
add_line(modelName, 'ComparePose/1', 'PoseCompareScope/1', 'autorouting', 'on');
add_line(modelName, 'ComparePose/1', 'PoseCompareToWorkspace/1', 'autorouting', 'on');

set_param(modelName, 'StopTime', '10', 'Solver', 'ode4', ...
    'FixedStep', '0.01', 'ReturnWorkspaceOutputs', 'on');
save_system(modelName, modelFile);

simOut = sim(modelName);
errorData = simOut.get('pose_error_ts');
compareData = simOut.get('pose_compare_ts');
referenceData = simOut.get('joint_reference_ts');
solutionData = simOut.get('joint_solution_ts');
t = errorData.Time;
errors = squeeze(errorData.Data);
positions = squeeze(compareData.Data);
qReference = squeeze(referenceData.Data);
qSolution = squeeze(solutionData.Data);
if size(errors,1) == 2, errors = errors.'; end
if size(positions,1) == 6, positions = positions.'; end
if size(qReference,1) == 6, qReference = qReference.'; end
if size(qSolution,1) == 6, qSolution = qSolution.'; end

fig = figure('Color', 'w', 'Name', 'Simulink IK-FK test');
tiledlayout(fig, 3, 2, 'TileSpacing', 'compact', 'Padding', 'compact');
nexttile;
plot(t, positions(:,1), t, positions(:,4), '--', 'LineWidth', 1.1); grid on;
xlabel('Time (s)'); ylabel('X (mm)'); title('X: target vs IK -> FK');
legend('Target','IK -> FK','Location','best');
nexttile;
plot(t, positions(:,2), t, positions(:,5), '--', 'LineWidth', 1.1); grid on;
xlabel('Time (s)'); ylabel('Y (mm)'); title('Y: target vs IK -> FK');
legend('Target','IK -> FK','Location','best');
nexttile;
plot(t, positions(:,3), t, positions(:,6), '--', 'LineWidth', 1.1); grid on;
xlabel('Time (s)'); ylabel('Z (mm)'); title('Z: target vs IK -> FK');
legend('Target','IK -> FK','Location','best');
nexttile;
plot(t, errors(:,1), 'LineWidth', 1.2); grid on;
xlabel('Time (s)'); ylabel('Position error (mm)'); title('Position residual');
ylim([0, 1e-3]);
nexttile;
plot(t, errors(:,2), 'LineWidth', 1.2); grid on;
xlabel('Time (s)'); ylabel('Orientation error (deg)'); title('Orientation residual');
ylim([0, 1e-4]);
nexttile;
plot(t, rad2deg(qSolution), 'LineWidth', 1.0); grid on;
xlabel('Time (s)'); ylabel('Joint angle (deg)'); title('IK joint angles');
legend('q1','q2','q3','q4','q5','q6','Location','best');
exportgraphics(fig, plotFile, 'Resolution', 160);

fprintf('Simulink IK-FK model saved: %s\n', modelFile);
fprintf('IK-FK test plot saved: %s\n', plotFile);
fprintf('Samples: %d; max position error: %.6g mm; max orientation error: %.6g deg\n', ...
    numel(t), max(errors(:,1)), max(errors(:,2)));
